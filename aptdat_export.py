def _marker_row(m: Marker):
    return (m.kind, _clean(m.name), round(m.pos[0], 4), round(m.pos[1], 4), round(m.height_m, 4),
            None if m.heading_deg is None else round(m.heading_deg, 3), m.props)


def _info(airport: AirportData) -> dict:
    return {
        "icao": _clean(airport.icao), "name": _clean(airport.name), "ref_lat": airport.ref_lat,
        "ref_lon": airport.ref_lon, "elevation_ft": airport.elevation_ft,
        "projection": airport.projection, "metadata": airport.metadata,
        "frequencies": [dataclasses.asdict(f) for f in airport.frequencies],
        "traffic_flows": airport.flows, "ignored_row_codes": airport.ignored,
    }


def export_blender_script(groups: Dict[str, Mesh], out_path: str, airport: AirportData,
                          markers: Optional[List[Marker]] = None) -> None:
    markers = markers or []
    with open(out_path, "w", encoding="utf-8", newline="\n") as f:
        f.write(_BLENDER_HEADER.replace("@ICAO@", _clean(airport.icao)).replace("@NAME@", _clean(airport.name))
                .replace("@LAT@", str(airport.ref_lat)).replace("@LON@", str(airport.ref_lon)))
        f.write(f"MARKER_LABELS = {MARKER_LABELS!r}\n\n")
        f.write(f"INFO = {_info(airport)!r}\n\n")
        f.write("MARKERS = [\n")
        for m in markers:
            row = _marker_row(m)
            f.write(f"    ({row[0]!r}, {row[1]!r}, {row[2]!r}, {row[3]!r}, {row[4]!r}, {row[5]!r}, {row[6]!r}),\n")
        f.write("]\n\n")
        f.write("# name: (category, colour, custom properties, vertices, triangles, wire edges)\n")
        f.write("GROUPS = {\n")
        for name, mesh in groups.items():
            if not mesh.vertices or not (mesh.faces or mesh.edges):
                continue
            safe_name = _clean(name).replace(" ", "_")
            verts_str = ", ".join(f"({x:.4f},{y:.4f},{z:.4f})" for (x, y, z) in mesh.vertices)
            faces_str = ", ".join(f"({a},{b},{c})" for (a, b, c) in mesh.faces)
            edges_str = ", ".join(f"({a},{b})" for (a, b) in mesh.edges)
            color = None if mesh.color is None else tuple(round(c, 3) for c in mesh.color)
            f.write(f"    {safe_name!r}: ({mesh.category!r}, {color!r}, {mesh.props!r}, "
                    f"[{verts_str}], [{faces_str}], [{edges_str}]),\n")
        f.write("}\n")
        f.write(_BLENDER_BODY)
        f.write("build()\n")


# --------------------------------------------------------------------------
# JSON dump of everything that was parsed
# --------------------------------------------------------------------------

def export_json(airport: AirportData, out_path: str) -> None:
    payload = dataclasses.asdict(airport)
    payload["units"] = "meters; x=east, y=north from the projection origin (see 'projection' for lat/lon)"
    with open(out_path, "w", encoding="utf-8", newline="\n") as f:
        json.dump(payload, f, indent=1)

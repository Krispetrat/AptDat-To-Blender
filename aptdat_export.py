"""
aptdat_export.py
-----------------
Turns the Mesh groups produced by aptdat_core.build_meshes() (plus the placed
Markers) into:
  - a .obj file (+ .mtl with colours). Each group becomes an OBJ "object", so it
    imports into Blender as separate, individually-selectable meshes. Wire groups
    (airport boundary, taxi route network) are written as OBJ line elements.
  - a standalone .py script that, when run from Blender's Scripting tab, rebuilds
    the same meshes natively with bpy + bmesh: one sub-collection per category,
    materials per colour, custom properties (surface, line type, ...) on every
    object, and Empties (with heading + properties) for signs / windsocks /
    startup locations / runway ends / ... .
  - a .json file with everything that was parsed (frequencies, ATC flows,
    metadata, taxi network, ...), in local metres plus the projection constants.

Blender note for the OBJ: the file is Z-up (X=east, Y=north, Z=up). In
Blender's OBJ importer set  Forward Axis = Y  and  Up Axis = Z  or the
layout will import standing on its edge. The Blender script has no such issue.
"""

import dataclasses
import json
import os
from typing import Dict, List, Optional

from aptdat_core import Mesh, Marker, AirportData, MARKER_LABELS


def _clean(text: str) -> str:
    return text.replace("\\", "/").replace('"', "'").replace("\n", " ").replace("\r", " ")


def _mat_name(color) -> str:
    return "aptdat_%02x%02x%02x" % tuple(int(round(c * 255)) for c in color)


def export_obj(groups: Dict[str, Mesh], out_path: str, airport: AirportData) -> None:
    colors = sorted({tuple(m.color) for m in groups.values() if m.color is not None})
    mtl_name = os.path.splitext(os.path.basename(out_path))[0] + ".mtl"
    if colors:
        with open(os.path.join(os.path.dirname(out_path) or ".", mtl_name), "w", encoding="utf-8", newline="\n") as f:
            f.write(f"# materials for {airport.icao}\n")
            for c in colors:
                f.write(f"newmtl {_mat_name(c)}\nKd {c[0]:.3f} {c[1]:.3f} {c[2]:.3f}\nKa 0 0 0\nKs 0 0 0\n\n")
    with open(out_path, "w", encoding="utf-8", newline="\n") as f:
        f.write(f"# {airport.icao} - {_clean(airport.name)}\n")
        f.write("# generated by apt.dat -> Blender layout tool\n")
        f.write(f"# reference point: lat {airport.ref_lat}, lon {airport.ref_lon}\n")
        f.write("# units: meters. X=east, Y=north, Z=up.\n")
        if colors:
            f.write(f"mtllib {mtl_name}\n")
        f.write("\n")
        vertex_offset = 0
        for name, mesh in groups.items():
            if not mesh.vertices or not (mesh.faces or mesh.edges):
                continue
            safe_name = name.replace(" ", "_")
            f.write(f"o {safe_name}\n")
            if mesh.color is not None:
                f.write(f"usemtl {_mat_name(mesh.color)}\n")
            for (x, y, z) in mesh.vertices:
                f.write(f"v {x:.4f} {y:.4f} {z:.4f}\n")
            for (a, b, c) in mesh.faces:
                f.write(f"f {a + 1 + vertex_offset} {b + 1 + vertex_offset} {c + 1 + vertex_offset}\n")
            for (a, b) in mesh.edges:
                f.write(f"l {a + 1 + vertex_offset} {b + 1 + vertex_offset}\n")
            f.write("\n")
            vertex_offset += len(mesh.vertices)



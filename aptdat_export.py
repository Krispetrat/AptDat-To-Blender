def export_blender_script(groups: Dict[str, Mesh], out_path: str, airport: AirportData) -> None:
    with open(out_path, "w", encoding="utf-8", newline="\n") as f:
        f.write(_BLENDER_SCRIPT_HEADER.format(
            icao=_clean(airport.icao), name=_clean(airport.name),
            ref_lat=airport.ref_lat, ref_lon=airport.ref_lon,
        ))
        f.write("GROUPS = {\n")
        for name, mesh in groups.items():
            if not mesh.vertices or not mesh.faces:
                continue
            safe_name = _clean(name).replace(" ", "_")
            verts_str = ", ".join(f"({x:.4f},{y:.4f},{z:.4f})" for (x, y, z) in mesh.vertices)
            faces_str = ", ".join(f"({a},{b},{c})" for (a, b, c) in mesh.faces)
            f.write(f'    "{safe_name}": ([{verts_str}], [{faces_str}]),\n')
        f.write("}\n\n")
        f.write("build()\n")
